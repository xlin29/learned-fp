    '      ctx.font = fontStr;',
    '      ctx.translate(x + fontSize / 2, y - fontSize / 2);',
    '      ctx.rotate(rot);',
    '      ctx.fillText(ch, -fontSize / 2, fontSize / 2);',
    '      ctx.restore();',
    '    }',
    '  }',
    '',
    '  // === Background pixel watermark: write (code,code,code,0) only on A==0 pixels ===',
  '  try {',
  '    const img = ctx.getImageData(0, 0, CANVAS_WIDTH, CANVAS_HEIGHT);',
  '    const d = img.data;',
  '    // Unify: code is bs (clamped to 1..254).',
  '    let code = ((cfg.bs ?? cfg.bsCode ?? cfg.brightnessShift) | 0);',
  '    if (code < 1) code = 1; else if (code > 254) code = 254;',
  '    const bsRaw = code;',
  '    const salt  = ((cfg.maskSalt|0)>>>0);',
  '    const D     = Number(cfg.D) || 80;',
  '    let sIdx    = 0;',
  '    if (Number.isFinite(cfg.sIdx) && cfg.sIdx > 0) {',
  '      sIdx = cfg.sIdx|0;',
  '    } else {',
  '      try { const m = String(name||"").match(/^S(\\d+)_/); if (m) sIdx = (m[1]|0); } catch {}',
  '    }',
  '    function xorshift32(u){ u|=0; u^=u<<13; u^=u>>>17; u^=u<<5; return u>>>0; }',
  '    for (let p = 0; p < d.length; p += 4) {',
  '      const a0 = d[p+3];',
  '      if (a0 !== 0) continue;',  
  '      // Optional: only write when the background gray is consistent — uncomment the next two lines to enable.',
  '      // const r0=d[p], g0=d[p+1], b0=d[p+2];',
  '      // if (r0!==g0 || g0!==b0) continue;',
  '      const idx = (p>>2);',
  '      const y = (idx / CANVAS_WIDTH) | 0;',
  '      const x = idx - y * CANVAS_WIDTH;',
  '      let seed = (((salt + bsRaw + (sIdx*1315423911))|0) ^ ((y<<16)|x))|0;',
  '      const h = xorshift32(seed);',
