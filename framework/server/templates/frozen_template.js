    '',
    '  const items = (cfg.items || []).slice(0, 36);',
    '',
    '  for (let row = 0; row < gridSize; row++) {',
    '    for (let col = 0; col < gridSize; col++) {',
    '      if (k >= items.length) break;',
    '',
    '      const raw = items[k++];',
    '      const it = (raw && typeof raw === "object") ? raw : {};',
    '',
    '      const add = Number(it.fontSize) || 0;',
