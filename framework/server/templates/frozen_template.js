    '        ch = String(it.ch);',
    '      } else if (Number.isInteger(it.cp) && Number.isInteger(it.cp2)) {',
    '        ch = String.fromCodePoint(it.cp, it.cp2);',
    '      } else if (Number.isInteger(it.cp)) {',
    '        ch = String.fromCodePoint(it.cp);',
    '      } else {',
    '        ch = "\\u25A1";',
    '      }',
    '',
    '      const dx = Number(it.dx) || 0;',
    '      const dy = Number(it.dy) || 0;',
    '      const rot = Number(it.rot) || 0;',
