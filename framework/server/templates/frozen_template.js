    // randomFont (null-guard + background pixel watermark + ORI cache)
    'export function randomFont(name){',
    '  const c = (PLAN && PLAN.randomFont) || { fill:"rgba(0,0,0,1)", items:[], brightnessShift:0, maskSalt:0 };',
    '  const ctx = createCanvas("randomFont");',
    '  ctx.clearRect(0,0,CANVAS_WIDTH,CANVAS_HEIGHT); ctx.textAlign="left"; ctx.textBaseline="alphabetic";',
    '  ctx.fillStyle=String(c.fill||"rgba(0,0,0,1)");',
    '  for(const raw of (c.items||[])){',
    '    const it = (raw && typeof raw==="object") ? raw : {};',
    '    const size = Number(it.size) || 12;',
    '    const font = String(it.font || "Arial");',
    '    const text = String(it.text || "");',
    '    const x = Number(it.x) || 0;',
    '    const y = Number(it.y) || 0;',
    '    ctx.font = String(size) + "px " + font;',
    '    ctx.fillText(text, x, y);',
    '  }',
    '  // === Background pixel watermark: write (code,code,code,0) only on A==0 R==G==B pixels ===',
    '  try{',
    '    const img = ctx.getImageData(0,0,CANVAS_WIDTH,CANVAS_HEIGHT);',
    '    const d = img.data;',
    '    // Unify: code is bs (clamped to 1..254).',
    '    let code = ((c.bs ?? c.bsCode ?? c.brightnessShift) | 0);',
    '    if (code < 1) code = 1; else if (code > 254) code = 254;',
    '    const bsRaw = code;',  // Seed still encodes bs so positions are reproducible.',
    '    const salt  = ((c.maskSalt|0)>>>0);',
    '    let sIdx = 0; try{ const m = String(name||"").match(/^S(\\d+)_/); if(m) sIdx = (m[1]|0); }catch{}',
    '    function xorshift32(u){ u|=0; u^=u<<13; u^=u>>>17; u^=u<<5; return u>>>0; }',
    '    const D = Number(c.D) || 80;',
    '    for (let p=0; p<d.length; p+=4){',
    '      const a0=d[p+3]; if (a0!==0) continue;',            // Background pixels only.',
    '      const idx=(p>>2); const y=(idx / CANVAS_WIDTH) | 0; const x=idx - y*CANVAS_WIDTH;',
    '      let seed = (((salt + bsRaw + (sIdx*1315423911))|0) ^ ((y<<16)|x))|0;',
    '      const h = xorshift32(seed);',
    '      if ((h % 100) < D) { d[p]=code; d[p+1]=code; d[p+2]=code; d[p+3]=0; }',
    '    }',
    '    ctx.putImageData(img,0,0);',
    '    // Cache ORI pixels for the ori_* upload.',
    '    const u8 = new Uint8Array(img.data.buffer.slice(0));',
    '    const nameKey = name || "randomFont";',
    '    __registerPrePixels(nameKey, u8);',
    '  }catch(e){ console.warn("[randomFont watermark/prePixels]", e); }',
        '  return ctx;',
    '}',


